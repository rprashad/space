#!/usr/bin/env python3
"""Generate native profiles from the shared palette; --check detects drift."""
import argparse
import json
from pathlib import Path
import plistlib

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
repo = Path(__file__).resolve().parents[2]
palette = json.loads((repo / 'linux_env/config/space/palette.json').read_text())
names = ['black', 'red', 'green', 'yellow', 'blue', 'purple', 'cyan', 'white']
colors = [palette[n] for n in names] + [palette['bright' + n.title()] for n in names]


def write(relative, data):
    target = repo / relative
    if isinstance(data, str):
        data = data.encode()
    if args.check:
        if not target.exists() or target.read_bytes() != data:
            raise SystemExit(f'Generated profile out of date: {relative}')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)


xr = '''! Generated by render-terminal-profiles.py; edit palette.json instead.
XTerm*termName: xterm-256color
XTerm*faceName: MesloLGS NF
XTerm*faceSize: 11
XTerm*utf8: 2
XTerm*renderFont: true
XTerm*utf8Fonts: true
XTerm*locale: true
XTerm*loginShell: true
XTerm*geometry: 120x34
XTerm*saveLines: 50000
XTerm*scrollBar: false
XTerm*scrollTtyOutput: false
XTerm*scrollKey: true
XTerm*cursorBlink: false
XTerm*fastScroll: true
XTerm*multiScroll: true
XTerm*allowPasteControls: false
XTerm*selectToClipboard: true
XTerm*highlightColorMode: true
XTerm*VT100.Translations: #override \\n\\
 Ctrl Shift <Key>C: copy-selection(CLIPBOARD) \\n\\
 Ctrl Shift <Key>V: insert-selection(CLIPBOARD) \\n\\
 Shift <Key>Insert: insert-selection(CLIPBOARD)
'''
for resource, name in [('background', 'background'), ('foreground', 'foreground'), ('cursorColor', 'cursorColor'), ('highlightColor', 'selectionBackground')]:
    xr += f'XTerm*{resource}: {palette[name]}\n'
xr += 'XTerm*highlightTextColor: #203149\n'
for i, value in enumerate(colors):
    xr += f'XTerm*color{i}: {value}\n'
write('linux_env/config/space/Xresources', xr)
toolbar = '''\n! WSL toolbar build (ignored by ordinary xterm builds).
XTerm*toolBar: true
XTerm*menubar*background: #293b53
XTerm*menubar*foreground: #f3f6fc
XTerm*mainMenu*background: #293b53
XTerm*mainMenu*foreground: #f3f6fc
XTerm*vtMenu*background: #293b53
XTerm*vtMenu*foreground: #f3f6fc
XTerm*fontMenu*background: #293b53
XTerm*fontMenu*foreground: #f3f6fc
XTerm*menubar*font: fixed
XTerm*SimpleMenu*font: fixed
XTerm*SmeBSB*font: fixed
'''
write('windows_env/config/Xresources', xr + toolbar)
kitty = '# Generated by render-terminal-profiles.py\nfont_family MesloLGS NF\nfont_size 11\n'
for key in ['background', 'foreground']:
    kitty += f'{key} {palette[key]}\n'
kitty += f'cursor {palette["cursorColor"]}\nselection_background {palette["selectionBackground"]}\nselection_foreground #203149\n'
kitty += 'cursor_blink_interval 0\nscrollback_lines 50000\nshell /bin/zsh -l\n'
kitty += ''.join(f'color{i} {c}\n' for i, c in enumerate(colors))
write('linux_env/config/kitty/space-navy.conf', kitty)


def components(value):
    return [int(value[i:i+2], 16) / 255 for i in (1, 3, 5)]


def nscolor(value):
    # Standard NSKeyedArchiver NSColor object used in Terminal.app exports.
    return plistlib.dumps({'$version': 100000, '$archiver': 'NSKeyedArchiver', '$top': {'root': plistlib.UID(1)},
        '$objects': ['$null', {'NSRGB': (' '.join(f'{x:.9f}' for x in components(value)) + '\0').encode(),
            'NSColorSpace': 2, '$class': plistlib.UID(2)}, {'$classname': 'NSColor', '$classes': ['NSColor', 'NSObject']}]}, fmt=plistlib.FMT_BINARY)


terminal = {'name': 'Space Navy', 'type': 'Window Settings', 'ProfileCurrentVersion': 2.07, 'TerminalType': 'nsterm-256color', 'columnCount': 120, 'rowCount': 34}
for key, name in [('BackgroundColor', 'background'), ('TextColor', 'foreground'), ('TextBoldColor', 'foreground'), ('CursorColor', 'cursorColor'), ('SelectionColor', 'selectionBackground')]:
    terminal[key] = nscolor(palette[name])
for i, name in enumerate(names):
    name = 'Magenta' if name == 'purple' else name.title()
    terminal['ANSI' + name + 'Color'] = nscolor(colors[i])
    terminal['ANSIBright' + name + 'Color'] = nscolor(colors[i + 8])
write('mac_env/config/Space Navy.terminal', plistlib.dumps(terminal))
profile = {'Name': 'Space Navy', 'Guid': '2280d9dc-b622-5b67-b16d-7631849ba212',
    'Normal Font': 'MesloLGS-NF-Regular 13', 'Non Ascii Font': 'MesloLGS-NF-Regular 13',
    'Terminal Type': 'xterm-256color', 'Rows': 34, 'Columns': 120, 'Scrollback Lines': 50000,
    'Blinking Cursor': False, 'Custom Command': 'Yes', 'Command': '/bin/zsh -l', 'Transparency': 0.0}
for key, name in [('Background Color', 'background'), ('Foreground Color', 'foreground'), ('Cursor Color', 'cursorColor'), ('Selection Color', 'selectionBackground')]:
    profile[key] = dict(zip(['Red Component', 'Green Component', 'Blue Component'], components(palette[name])), **{'Color Space': 'sRGB'})
for i, color in enumerate(colors):
    profile[f'Ansi {i} Color'] = dict(zip(['Red Component', 'Green Component', 'Blue Component'], components(color)), **{'Color Space': 'sRGB'})
write('mac_env/config/iterm2-space.json', json.dumps({'Profiles': [profile]}, indent=2) + '\n')
print('Profiles match palette.' if args.check else 'Generated native terminal profiles.')
